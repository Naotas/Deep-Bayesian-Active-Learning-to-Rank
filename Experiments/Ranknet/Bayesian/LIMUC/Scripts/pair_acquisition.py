"""Pair-acquisition utilities for RankNet active-learning experiments."""

import hashlib
from collections import Counter
from dataclasses import dataclass

import numpy as np
import pandas as pd

SUPPORTED_METHODS = {"original", "random", "predictive_entropy", "pair_bald"}


@dataclass(frozen=True)
class CandidateMetric:
    """Store one candidate comparison and its acquisition diagnostics."""

    anchor: str
    candidate: str
    pbar: float
    predictive_entropy: float
    mean_conditional_entropy: float
    bald: float
    acquisition_score: float


def canonical_pair(left: str, right: str) -> tuple:
    """Return an order-independent image-pair key.

    Args:
        left (str): First image ID.
        right (str): Second image ID.

    Returns:
        tuple: Lexicographically ordered image IDs.
    """
    return tuple(sorted((str(left), str(right))))


def acquired_pair_keys(pair_data: pd.DataFrame) -> set:
    """Build canonical keys from an existing pair table.

    Args:
        pair_data (pd.DataFrame): Table containing ``x1_image`` and ``x2_image``.

    Returns:
        set: Order-independent pair keys.

    Raises:
        ValueError: If required columns or valid non-self pairs are missing.
    """
    required = {"x1_image", "x2_image"}
    missing = required - set(pair_data.columns)
    if missing:
        raise ValueError(f"Pair data is missing columns: {sorted(missing)}")

    # Legacy AL_0 files can contain both orientations of the same pair because
    # they were created by a derangement. They remain valid historical rows,
    # but collapse to one key for all future acquisition checks.
    keys = set()
    for left, right in pair_data[["x1_image", "x2_image"]].itertuples(
        index=False, name=None
    ):
        left = str(left)
        right = str(right)
        if left == right:
            raise ValueError(f"Existing pair data contains a self-comparison: {left}")
        key = canonical_pair(left, right)
        keys.add(key)
    return keys


def stable_sigmoid(values):
    """Calculate a numerically stable sigmoid.

    Args:
        values: Numeric NumPy-compatible values.

    Returns:
        np.ndarray: Sigmoid probabilities.
    """
    values = np.asarray(values, dtype=np.float64)
    probabilities = np.empty_like(values)
    positive = values >= 0
    probabilities[positive] = 1.0 / (1.0 + np.exp(-values[positive]))
    exp_values = np.exp(values[~positive])
    probabilities[~positive] = exp_values / (1.0 + exp_values)
    return probabilities


def binary_entropy(probabilities):
    """Calculate Bernoulli entropy using natural logarithms.

    Args:
        probabilities: Bernoulli probabilities.

    Returns:
        np.ndarray: Entropy in nats with the same shape as the input.

    Raises:
        ValueError: If a probability is non-finite or outside ``[0, 1]``.
    """
    probabilities = np.asarray(probabilities, dtype=np.float64)
    if not np.all(np.isfinite(probabilities)):
        raise ValueError("Probabilities contain NaN or infinity.")
    if np.any((probabilities < 0.0) | (probabilities > 1.0)):
        raise ValueError("Probabilities must be within [0, 1].")

    result = np.zeros_like(probabilities)
    interior = (probabilities > 0.0) & (probabilities < 1.0)
    values = probabilities[interior]
    result[interior] = -values * np.log(values) - (1.0 - values) * np.log1p(-values)
    return result


def calculate_pair_metrics(
    anchor_scores,
    candidate_scores,
    negative_tolerance: float = 1e-12,
) -> dict:
    """Calculate predictive entropy and Pair-BALD from aligned MC samples.

    ``anchor_scores[t]`` and ``candidate_scores[t, j]`` must be generated by the
    same model-parameter sample ``t``. The function averages comparison
    probabilities after applying the sigmoid; it never applies the sigmoid to
    an averaged score difference.

    Args:
        anchor_scores: One score per MC model sample with shape ``(T,)``.
        candidate_scores: Candidate scores with shape ``(T, candidates)``.
        negative_tolerance (float): Small negative BALD values within this
            tolerance are treated as floating-point roundoff and set to zero.

    Returns:
        dict: Arrays named ``pbar``, ``predictive_entropy``,
        ``mean_conditional_entropy``, and ``bald``.

    Raises:
        FloatingPointError: If a materially negative BALD value is observed.
        ValueError: If shapes or numeric values are invalid.
    """
    anchor_scores = np.asarray(anchor_scores, dtype=np.float64)
    candidate_scores = np.asarray(candidate_scores, dtype=np.float64)
    if anchor_scores.ndim != 1:
        raise ValueError("anchor_scores must have shape (T,).")
    if candidate_scores.ndim != 2:
        raise ValueError("candidate_scores must have shape (T, candidates).")
    if candidate_scores.shape[0] != anchor_scores.shape[0]:
        raise ValueError("Anchor and candidate MC sample counts differ.")
    if negative_tolerance < 0:
        raise ValueError("negative_tolerance must be non-negative.")
    if not np.all(np.isfinite(anchor_scores)) or not np.all(
        np.isfinite(candidate_scores)
    ):
        raise ValueError("MC scores contain NaN or infinity.")

    comparison_probabilities = stable_sigmoid(
        anchor_scores[:, np.newaxis] - candidate_scores
    )
    pbar = comparison_probabilities.mean(axis=0)
    predictive_entropy = binary_entropy(pbar)
    mean_conditional_entropy = binary_entropy(comparison_probabilities).mean(axis=0)
    bald = predictive_entropy - mean_conditional_entropy

    materially_negative = bald < -negative_tolerance
    if np.any(materially_negative):
        minimum = float(bald.min())
        raise FloatingPointError(
            "Pair-BALD became materially negative "
            f"(minimum={minimum:.17g}, tolerance={negative_tolerance:.17g})."
        )
    bald[(bald < 0.0) & ~materially_negative] = 0.0

    return {
        "pbar": pbar,
        "predictive_entropy": predictive_entropy,
        "mean_conditional_entropy": mean_conditional_entropy,
        "bald": bald,
    }


def _random_priorities(seed: int, anchor: str, size: int):
    digest = hashlib.sha256(f"{seed}\0{anchor}".encode()).digest()
    anchor_seed = int.from_bytes(digest[:4], byteorder="little", signed=False)
    return np.random.RandomState(anchor_seed).random_sample(size)


def build_candidate_rankings(
    anchors,
    candidates,
    method: str,
    acquired_pairs,
    score_by_image=None,
    seed: int = 240119,
    chunk_size: int = 2048,
    negative_tolerance: float = 1e-12,
):
    """Rank eligible comparison partners for every anchor image.

    Args:
        anchors: Ordered anchor image IDs.
        candidates: Candidate image IDs. Their order defines score-cache columns.
        method (str): ``original``, ``random``, ``predictive_entropy``, or
            ``pair_bald``.
        acquired_pairs: Canonical keys for previously acquired pairs.
        score_by_image: Optional mapping from image ID to aligned MC score arrays.
        seed (int): Random seed used by uniform random acquisition.
        chunk_size (int): Number of candidates scored at once.
        negative_tolerance (float): Roundoff tolerance for negative BALD values.

    Returns:
        dict: Anchor IDs mapped to acquisition-ordered ``CandidateMetric`` lists.

    Raises:
        ValueError: If inputs are invalid or MC scores are missing.
    """
    if method not in SUPPORTED_METHODS:
        raise ValueError(f"Unsupported pair-acquisition method: {method}")
    if chunk_size < 1:
        raise ValueError("chunk_size must be at least 1.")

    anchors = [str(value) for value in anchors]
    candidates = sorted({str(value) for value in candidates})
    if len(anchors) != len(set(anchors)):
        raise ValueError("Anchor image IDs must be unique.")

    needs_scores = method in {"predictive_entropy", "pair_bald"}
    if needs_scores and score_by_image is None:
        raise ValueError(f"{method} requires aligned MC score samples.")

    rankings = {}
    acquired_pairs = set(acquired_pairs)
    for anchor in anchors:
        eligible = [
            candidate
            for candidate in candidates
            if candidate != anchor
            and canonical_pair(anchor, candidate) not in acquired_pairs
        ]
        if not eligible:
            rankings[anchor] = []
            continue

        random_values = _random_priorities(seed, anchor, len(eligible))
        records = []
        for start in range(0, len(eligible), chunk_size):
            chunk = eligible[start : start + chunk_size]
            if score_by_image is None:
                metrics = {
                    name: np.full(len(chunk), np.nan)
                    for name in [
                        "pbar",
                        "predictive_entropy",
                        "mean_conditional_entropy",
                        "bald",
                    ]
                }
            else:
                anchor_scores = np.asarray(score_by_image[anchor], dtype=np.float64)
                candidate_scores = np.column_stack(
                    [
                        np.asarray(score_by_image[name], dtype=np.float64)
                        for name in chunk
                    ]
                )
                metrics = calculate_pair_metrics(
                    anchor_scores,
                    candidate_scores,
                    negative_tolerance=negative_tolerance,
                )

            for offset, candidate in enumerate(chunk):
                index = start + offset
                if method in {"original", "random"}:
                    acquisition_score = random_values[index]
                elif method == "predictive_entropy":
                    acquisition_score = metrics["predictive_entropy"][offset]
                else:
                    acquisition_score = metrics["bald"][offset]
                records.append(
                    CandidateMetric(
                        anchor=anchor,
                        candidate=candidate,
                        pbar=float(metrics["pbar"][offset]),
                        predictive_entropy=float(metrics["predictive_entropy"][offset]),
                        mean_conditional_entropy=float(
                            metrics["mean_conditional_entropy"][offset]
                        ),
                        bald=float(metrics["bald"][offset]),
                        acquisition_score=float(acquisition_score),
                    )
                )

        rankings[anchor] = sorted(
            records,
            key=lambda record: (-record.acquisition_score, record.candidate),
        )
    return rankings


def select_ranked_pairs(
    rankings,
    budget: int,
    acquired_pairs,
    previous_partner_counts=None,
    partner_cap: int = 0,
):
    """Select unique pairs while making every anchor appear at least once.

    The first pass visits anchors in their supplied order and selects each
    anchor's highest-ranked feasible partner. Remaining budget is assigned to
    the globally highest-ranked feasible pair. A cap of zero means unlimited
    partner appearances.

    Args:
        rankings: Ordered mapping returned by ``build_candidate_rankings``.
        budget (int): Exact number of new comparisons to acquire.
        acquired_pairs: Canonical keys for previously acquired pairs.
        previous_partner_counts: Existing appearances in the ``x2_image`` role.
        partner_cap (int): Maximum cumulative ``x2_image`` appearances per image;
            zero disables the cap.

    Returns:
        list[CandidateMetric]: Selected comparisons in acquisition order.

    Raises:
        RuntimeError: If the exact budget and coverage constraints cannot be met.
        ValueError: If budget or cap is invalid.
    """
    anchors = list(rankings)
    if budget < len(anchors):
        raise RuntimeError(
            f"Pair budget {budget} is smaller than the {len(anchors)} anchors; "
            "each anchor must appear at least once."
        )
    if budget < 1:
        raise ValueError("budget must be at least 1.")
    if partner_cap < 0:
        raise ValueError("partner_cap must be non-negative.")

    used_pairs = set(acquired_pairs)
    partner_counts = Counter(previous_partner_counts or {})
    selected = []

    def feasible(record):
        pair_key = canonical_pair(record.anchor, record.candidate)
        under_cap = partner_cap == 0 or partner_counts[record.candidate] < partner_cap
        return pair_key not in used_pairs and under_cap

    for anchor in anchors:
        record = next((item for item in rankings[anchor] if feasible(item)), None)
        if record is None:
            raise RuntimeError(
                "Cannot cover every anchor under the duplicate and partner-cap "
                f"constraints. No feasible partner remains for anchor {anchor!r}."
            )
        selected.append(record)
        used_pairs.add(canonical_pair(record.anchor, record.candidate))
        partner_counts[record.candidate] += 1

    while len(selected) < budget:
        best = None
        for anchor in anchors:
            candidate = next(
                (item for item in rankings[anchor] if feasible(item)),
                None,
            )
            if candidate is None:
                continue
            key = (-candidate.acquisition_score, candidate.anchor, candidate.candidate)
            if best is None or key < best[0]:
                best = (key, candidate)
        if best is None:
            raise RuntimeError(
                f"Only {len(selected)} of {budget} requested pairs are feasible "
                "under the duplicate and partner-cap constraints."
            )
        record = best[1]
        selected.append(record)
        used_pairs.add(canonical_pair(record.anchor, record.candidate))
        partner_counts[record.candidate] += 1

    return selected


def metrics_frame(rankings, selected):
    """Convert candidate rankings into a persistable diagnostics table.

    Args:
        rankings: Mapping returned by ``build_candidate_rankings``.
        selected: Selected ``CandidateMetric`` objects.

    Returns:
        pd.DataFrame: Per-candidate acquisition diagnostics.
    """
    selected_keys = {
        (record.anchor, record.candidate): index
        for index, record in enumerate(selected, start=1)
    }
    rows = []
    for anchor_records in rankings.values():
        for rank, record in enumerate(anchor_records, start=1):
            rows.append(
                {
                    "anchor_image": record.anchor,
                    "candidate_image": record.candidate,
                    "candidate_rank": rank,
                    "pbar": record.pbar,
                    "predictive_entropy": record.predictive_entropy,
                    "mean_conditional_entropy": record.mean_conditional_entropy,
                    "bald": record.bald,
                    "acquisition_score": record.acquisition_score,
                    "selected": int((record.anchor, record.candidate) in selected_keys),
                    "selection_order": selected_keys.get(
                        (record.anchor, record.candidate)
                    ),
                }
            )
    return pd.DataFrame(rows)


def selected_pairs_frame(selected):
    """Convert selected acquisition records to an unlabeled pair table.

    Args:
        selected: Selected ``CandidateMetric`` objects.

    Returns:
        pd.DataFrame: Pair IDs and acquisition diagnostics without oracle labels.
    """
    return pd.DataFrame(
        [
            {
                "x1_image": record.anchor,
                "x2_image": record.candidate,
                "pbar": record.pbar,
                "predictive_entropy": record.predictive_entropy,
                "mean_conditional_entropy": record.mean_conditional_entropy,
                "bald": record.bald,
                "acquisition_score": record.acquisition_score,
            }
            for record in selected
        ]
    )


def apply_mayo_oracle(unlabeled_pairs: pd.DataFrame, labels_by_image) -> pd.DataFrame:
    """Attach RankNet targets after pair acquisition has finished.

    Args:
        unlabeled_pairs (pd.DataFrame): Pair table containing only image IDs and
            optional acquisition diagnostics.
        labels_by_image: Mapping from image ID to Mayo grade.

    Returns:
        pd.DataFrame: Pair table with ``x1_label``, ``x2_label``, and the existing
        ``relative_label`` convention: 1, 0.5, or 0.

    Raises:
        ValueError: If pair columns or oracle labels are missing.
    """
    required = {"x1_image", "x2_image"}
    missing = required - set(unlabeled_pairs.columns)
    if missing:
        raise ValueError(f"Unlabeled pair data is missing columns: {sorted(missing)}")

    output = unlabeled_pairs.copy()
    missing_images = sorted(
        (set(output["x1_image"].astype(str)) | set(output["x2_image"].astype(str)))
        - set(labels_by_image)
    )
    if missing_images:
        raise ValueError(f"Mayo oracle labels are missing for: {missing_images}")

    x1_labels = output["x1_image"].astype(str).map(labels_by_image).astype(float)
    x2_labels = output["x2_image"].astype(str).map(labels_by_image).astype(float)
    differences = x1_labels.to_numpy() - x2_labels.to_numpy()
    relative_labels = np.full(len(output), 0.5, dtype=np.float64)
    relative_labels[differences > 0] = 1.0
    relative_labels[differences < 0] = 0.0
    output.insert(2, "x1_label", x1_labels)
    output.insert(3, "x2_label", x2_labels)
    output.insert(4, "relative_label", relative_labels)
    return output


def summarize_pairs(pair_data: pd.DataFrame) -> dict:
    """Summarize comparison counts, grade relationships, and graph connectivity.

    Args:
        pair_data (pd.DataFrame): Oracle-labeled cumulative pair data.

    Returns:
        dict: Scalar experiment summary values.
    """
    required = {"x1_image", "x2_image", "x1_label", "x2_label"}
    missing = required - set(pair_data.columns)
    if missing:
        raise ValueError(f"Pair data is missing columns: {sorted(missing)}")

    parent = {}

    def find(node):
        parent.setdefault(node, node)
        while parent[node] != node:
            parent[node] = parent[parent[node]]
            node = parent[node]
        return node

    def union(left, right):
        left_root = find(left)
        right_root = find(right)
        if left_root != right_root:
            parent[right_root] = left_root

    for left, right in pair_data[["x1_image", "x2_image"]].itertuples(
        index=False, name=None
    ):
        union(str(left), str(right))

    components = len({find(node) for node in parent})
    grade_distance = np.abs(
        pair_data["x1_label"].to_numpy(dtype=float)
        - pair_data["x2_label"].to_numpy(dtype=float)
    )
    pair_count = len(pair_data)
    unique_images = len(
        set(pair_data["x1_image"].astype(str)) | set(pair_data["x2_image"].astype(str))
    )
    denominator = max(pair_count, 1)
    return {
        "cumulative_pair_count": pair_count,
        "unique_image_count": unique_images,
        "connected_component_count": components,
        "tie_pair_count": int(np.sum(grade_distance == 0)),
        "adjacent_pair_count": int(np.sum(grade_distance == 1)),
        "distant_pair_count": int(np.sum(grade_distance >= 2)),
        "tie_pair_fraction": float(np.sum(grade_distance == 0) / denominator),
        "adjacent_pair_fraction": float(np.sum(grade_distance == 1) / denominator),
        "distant_pair_fraction": float(np.sum(grade_distance >= 2) / denominator),
    }


def image_appearance_counts(pair_data: pd.DataFrame) -> pd.DataFrame:
    """Count total, anchor, and partner appearances for every image.

    Args:
        pair_data (pd.DataFrame): Pair data with image ID columns.

    Returns:
        pd.DataFrame: Appearance counts sorted by image ID.
    """
    x1_counts = Counter(pair_data["x1_image"].astype(str))
    x2_counts = Counter(pair_data["x2_image"].astype(str))
    return pd.DataFrame(
        [
            {
                "filename": name,
                "anchor_appearances": x1_counts[name],
                "partner_appearances": x2_counts[name],
                "total_appearances": x1_counts[name] + x2_counts[name],
            }
            for name in sorted(set(x1_counts) | set(x2_counts))
        ]
    )
